const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

// Split the statement into words so they can light up one by one. Re-run after a language change.
function splitWords() {
  document.querySelectorAll("[data-words]").forEach(element => {
    const text = element.textContent.trim();
    element.setAttribute("aria-label", text);
    element.replaceChildren(...text.split(/\s+/).flatMap((word, index) => {
      const span = document.createElement("span");
      span.className = "word";
      span.setAttribute("aria-hidden", "true");
      span.textContent = word;
      return index ? [document.createTextNode(" "), span] : [span];
    }));
  });
  requestScroll();
}

// One scroll loop drives every scroll-linked effect.
const tilt = document.querySelector("[data-tilt]");
const rise = document.querySelector("[data-rise]");
const clamp = value => Math.min(1, Math.max(0, value));
let scheduled = false;
function updateScroll() {
  scheduled = false;
  if (reduceMotion) return;
  const vh = window.innerHeight;
  if (tilt) {
    const top = tilt.getBoundingClientRect().top;
    tilt.style.setProperty("--p", clamp(1 - (top - vh * .18) / (vh * .55)).toFixed(3));
  }
  if (rise) {
    const top = rise.getBoundingClientRect().top;
    rise.style.setProperty("--p", clamp(1 - (top - vh * .25) / (vh * .6)).toFixed(3));
  }
  document.querySelectorAll("[data-words]").forEach(element => {
    const box = element.getBoundingClientRect();
    const progress = clamp((vh * .85 - box.top) / (box.height + vh * .35));
    const words = element.querySelectorAll(".word");
    const lit = Math.round(progress * words.length);
    words.forEach((word, index) => word.classList.toggle("is-lit", index < lit));
  });
}
const requestScroll = () => { if (!scheduled) { scheduled = true; requestAnimationFrame(updateScroll); } };
window.addEventListener("scroll", requestScroll, { passive: true });
window.addEventListener("resize", requestScroll);
setLanguage(initialLanguage);

// The sticky screen follows whichever chapter is in the middle of the viewport.
const chapters = document.querySelectorAll("[data-chapter]");
if (chapters.length && typeof IntersectionObserver !== "undefined") {
  const stages = document.querySelectorAll("[data-stage]");
  const chapterObserver = new IntersectionObserver(entries => {
    for (const entry of entries) {
      if (!entry.isIntersecting) continue;
      const name = entry.target.dataset.chapter;
      chapters.forEach(chapter => chapter.classList.toggle("is-active", chapter === entry.target));
      stages.forEach(stage => {
        stage.classList.toggle("is-active", stage.dataset.stage === name);
        syncDemoVideo(stage);
      });
    }
  }, { rootMargin: "-45% 0px -45% 0px" });
  chapters.forEach(chapter => chapterObserver.observe(chapter));
}

// Demo clips: muted, play only while shown, and step through data-sources in turn.
function demoVideoShown(video) {
  if (video.closest(".stage-screen")) return video.classList.contains("is-active") && video.dataset.inView === "1";
  return video.dataset.inView === "1";
}
function syncDemoVideo(video) {
  if (!(video instanceof HTMLVideoElement)) return;
  if (reduceMotion) { video.controls = true; return; }
  if (demoVideoShown(video) && video.offsetParent !== null) {
    if (video.preload === "none") video.preload = "auto";
    const playing = video.play();
    if (playing && playing.catch) playing.catch(() => {});
  } else {
    video.pause();
  }
}
const demoVideos = document.querySelectorAll("video.demo-video");
demoVideos.forEach(video => {
  const sources = (video.dataset.sources || "").split(",").filter(Boolean);
  let index = 0;
  video.addEventListener("ended", () => {
    if (sources.length > 1) {
      index = (index + 1) % sources.length;
      video.src = `./videos/${sources[index]}.mp4`;
      video.poster = `./videos/${sources[index]}.webp`;
    } else {
      video.currentTime = 0;
    }
    syncDemoVideo(video);
  });
});
if (reduceMotion) {
  demoVideos.forEach(video => { video.controls = true; });
} else if (typeof IntersectionObserver !== "undefined") {
  const videoObserver = new IntersectionObserver(entries => {
    for (const entry of entries) {
      entry.target.dataset.inView = entry.isIntersecting ? "1" : "0";
      syncDemoVideo(entry.target);
    }
  }, { threshold: 0.25 });
  demoVideos.forEach(video => videoObserver.observe(video));
}

if (typeof IntersectionObserver !== "undefined" && !reduceMotion) {
  const revealObserver = new IntersectionObserver(entries => {
    for (const entry of entries) {
      if (!entry.isIntersecting) continue;
      entry.target.classList.add("is-visible");
      revealObserver.unobserve(entry.target);
    }
  }, { threshold: 0.12, rootMargin: "0px 0px -28px 0px" });
  document.querySelectorAll("[data-reveal]").forEach(element => {
    element.classList.add("reveal-ready");
    revealObserver.observe(element);
  });
}
