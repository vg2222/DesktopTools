const supportedLanguages = Object.keys(translations);
const params = new URLSearchParams(window.location.search);
const requestedLanguage = params.get("lang");
let savedLanguage;
try { savedLanguage = localStorage.getItem("desktoptools-site-language"); } catch { /* Storage can be unavailable. */ }
const browserLanguage = navigator.language?.split("-")[0];
const initialLanguage = [requestedLanguage, savedLanguage, browserLanguage, "en"].find(value => supportedLanguages.includes(value));
const selector = document.getElementById("language");

function setLanguage(language, updateUrl = false) {
  const chosen = supportedLanguages.includes(language) ? language : "en";
  const copy = translations[chosen];
  document.documentElement.lang = chosen;
  const isSupportPage = document.documentElement.dataset?.page === "support";
  document.title = isSupportPage ? copy.supportTitle : copy.pageTitle;
  document.querySelector('meta[name="description"]').content = isSupportPage ? copy.supportDescription : copy.description;
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const value = copy[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach(element => {
    const value = copy[element.dataset.i18nAlt];
    if (value) element.alt = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(element => {
    const value = copy[element.dataset.i18nAria];
    if (value) element.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-language-link]").forEach(link => {
    const url = new URL(link.href);
    if (chosen === "en") url.searchParams.delete("lang");
    else url.searchParams.set("lang", chosen);
    link.href = url.href;
  });
  document.querySelectorAll('[data-i18n-wallet]').forEach(element => {
    element.textContent = copy.sendOnly.replace('{coin}', element.dataset.coin).replace('{network}', element.dataset.network);
  });
  selector.value = chosen;
  try { localStorage.setItem("desktoptools-site-language", chosen); } catch { /* Storage can be unavailable. */ }
  if (updateUrl) {
    const url = new URL(window.location.href);
    if (chosen === "en") url.searchParams.delete("lang");
    else url.searchParams.set("lang", chosen);
    history.replaceState(null, "", url);
  }
}

const header = document.querySelector(".site-header");
if (header) {
  const markScrolled = () => header.classList.toggle("is-scrolled", window.scrollY > 8);
  markScrolled();
  window.addEventListener("scroll", markScrolled, { passive: true });
}

selector.addEventListener("change", event => setLanguage(event.target.value, true));
setLanguage(initialLanguage);

if (typeof IntersectionObserver !== "undefined" && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
  const revealObserver = new IntersectionObserver(entries => {
    for (const entry of entries) {
      if (!entry.isIntersecting) continue;
      entry.target.classList.add("is-visible");
      revealObserver.unobserve(entry.target);
    }
  }, { threshold: 0.12, rootMargin: "0px 0px -28px 0px" });
  document.querySelectorAll("[data-reveal]").forEach(element => {
    element.classList.add("reveal-ready");
    revealObserver.observe(element);
  });
}
